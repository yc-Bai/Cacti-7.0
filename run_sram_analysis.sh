#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEFAULT_SINGLE_OUT_DIR="runs/sram_single"
DEFAULT_BATCH_OUT_DIR="runs/sram_batch"
SUMMARY_PATH=""
OUT_DIR=""

usage() {
  cat <<'EOF'
Usage:
  ./run_sram_analysis.sh single <config.conf> [--out-dir DIR] [--summary FILE]
  ./run_sram_analysis.sh batch  <batch.csv>   [--out-dir DIR] [--summary FILE]
  ./run_sram_analysis.sh help

Single config files use trusted Bash KEY=value syntax. Batch files use simple CSV
with no embedded commas or quoted commas.

Required single config keys:
  RUN_NAME, PORT_MODE, WIDTH_BITS, DEPTH_WORDS

Required batch CSV columns:
  run_name, port_mode, width_bits, depth_words

PORT_MODE values:
  single  -> one read/write port (1RW)
  dual    -> one exclusive read port plus one exclusive write port (1R1W)
EOF
}

die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

require_tools() {
  local tool
  for tool in awk sed grep mkdir date make; do
    command -v "$tool" >/dev/null 2>&1 || die "required tool not found: $tool"
  done
}

ensure_cacti_binary() {
  if [[ -x "$SCRIPT_DIR/cacti" ]]; then
    return
  fi

  printf 'CACTI binary not found; running make...\n'
  (cd "$SCRIPT_DIR" && make)

  [[ -x "$SCRIPT_DIR/cacti" ]] || die "make completed but ./cacti is not executable"
}

sanitize_run_name() {
  printf '%s' "$1" | sed 's/[^A-Za-z0-9_.-]/_/g'
}

ceil_div() {
  local n="$1"
  local d="$2"
  printf '%d' $(((n + d - 1) / d))
}

csv_escape() {
  local value="${1:-}"
  if [[ "$value" == *','* || "$value" == *'"'* || "$value" == *$'\n'* || "$value" == *$'\r'* ]]; then
    value="${value//\"/\"\"}"
    printf '"%s"' "$value"
  else
    printf '%s' "$value"
  fi
}

csv_row() {
  local first=1
  local value
  for value in "$@"; do
    if [[ "$first" -eq 0 ]]; then
      printf ','
    fi
    csv_escape "$value"
    first=0
  done
  printf '\n'
}

set_defaults() {
  RUN_NAME="${RUN_NAME:-sram_run}"
  PORT_MODE="${PORT_MODE:-single}"
  WIDTH_BITS="${WIDTH_BITS:-64}"
  DEPTH_WORDS="${DEPTH_WORDS:-1024}"
  TECH_UM="${TECH_UM:-0.028}"
  TEMPERATURE_K="${TEMPERATURE_K:-360}"
  DATA_CELL_TYPE="${DATA_CELL_TYPE:-itrs-hp}"
  DATA_PERIPHERAL_TYPE="${DATA_PERIPHERAL_TYPE:-itrs-hp}"
  FREQUENCY_MHZ="${FREQUENCY_MHZ:-500}"
  READ_ACTIVITY="${READ_ACTIVITY:-1.0}"
  WRITE_ACTIVITY="${WRITE_ACTIVITY:-0.0}"
  UCA_BANK_COUNT="${UCA_BANK_COUNT:-1}"
  WIRE_SIGNALING="${WIRE_SIGNALING:-Global_30}"
  WIRE_INSIDE_MAT="${WIRE_INSIDE_MAT:-semi-global}"
  WIRE_OUTSIDE_MAT="${WIRE_OUTSIDE_MAT:-semi-global}"
  INTERCONNECT_PROJECTION="${INTERCONNECT_PROJECTION:-conservative}"
  PRINT_LEVEL="${PRINT_LEVEL:-DETAILED}"
  FORCE_CACHE_CONFIG="${FORCE_CACHE_CONFIG:-false}"
  NDWL="${NDWL:-1}"
  NDBL="${NDBL:-1}"
  NSPD="${NSPD:-0}"
  NDCM="${NDCM:-1}"
  NDSAM1="${NDSAM1:-0}"
  NDSAM2="${NDSAM2:-0}"
}

require_positive_int() {
  local name="$1"
  local value="$2"
  [[ "$value" =~ ^[0-9]+$ ]] || die "$name must be a positive integer, got '$value'"
  ((value > 0)) || die "$name must be greater than zero"
}

derive_geometry() {
  require_positive_int WIDTH_BITS "$WIDTH_BITS"
  require_positive_int DEPTH_WORDS "$DEPTH_WORDS"

  BLOCK_SIZE_BYTES="$(ceil_div "$WIDTH_BITS" 8)"
  SIZE_BYTES=$((DEPTH_WORDS * BLOCK_SIZE_BYTES))
  PADDED_WIDTH_BITS=$((BLOCK_SIZE_BYTES * 8))
  PADDING_BITS_PER_WORD=$((PADDED_WIDTH_BITS - WIDTH_BITS))
  TOTAL_LOGICAL_BITS=$((DEPTH_WORDS * WIDTH_BITS))
  TOTAL_PADDED_BITS=$((DEPTH_WORDS * PADDED_WIDTH_BITS))
}

derive_ports() {
  case "$PORT_MODE" in
    single)
      RW_PORTS=1
      READ_PORTS=0
      WRITE_PORTS=0
      ;;
    dual)
      RW_PORTS=0
      READ_PORTS=1
      WRITE_PORTS=1
      ;;
    *)
      die "PORT_MODE must be 'single' or 'dual', got '$PORT_MODE'"
      ;;
  esac
}

